/**
 * codeExporter.js
 * 1-Click PNG Download and Roblox Studio Luau SurfaceAppearance script generator.
 */

export class CodeExporter {
  /**
   * Download the canvas as 1024x1024 PNG
   * @param {HTMLCanvasElement} canvas
   * @param {string} filename
   */
  static downloadPNG(canvas, filename = 'Roblox_Accessory_EmissiveMask.png') {
    if (!canvas || canvas.width === 0) return;

    // Create a clean offscreen 1024x1024 canvas to ensure exact dimensions
    const exportCanvas = document.createElement('canvas');
    exportCanvas.width = 1024;
    exportCanvas.height = 1024;
    const ctx = exportCanvas.getContext('2d');
    ctx.drawImage(canvas, 0, 0, 1024, 1024);

    const link = document.createElement('a');
    link.download = filename;
    link.href = exportCanvas.toDataURL('image/png');
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
  }

  /**
   * Generate Roblox Studio Lua script for SurfaceAppearance attachment
   * @param {Object} options
   * @returns {string} Luau code
   */
  static generateRobloxLua({
    emissiveAssetId = 'rbxassetid://YOUR_UPLOADED_EMISSIVE_ID',
    diffuseAssetId = 'rbxassetid://YOUR_DIFFUSE_ID',
    emissiveStrength = 1.5
  }) {
    return `--[[
  Roblox SurfaceAppearance Setup Script
  Generated by Roblox EmissiveMask Studio
  
  Cara Penggunaan di Roblox Studio:
  1. Upload file EmissiveMask PNG ke Asset Manager / Creator Dashboard (Image/Decal).
  2. Masukkan ID tekstur pada properti EmissiveMaskContent di bawah.
  3. Pilih accessory MeshPart Anda di Explorer, lalu paste skrip ini di Command Bar!
--]]

local Selection = game:GetService("Selection")
local selectedObjects = Selection:Get()

if #selectedObjects == 0 then
    warn("[EmissiveStudio] Pilih MeshPart atau Accessory di Explorer terlebih dahulu!")
    return
end

for _, obj in ipairs(selectedObjects) do
    local meshPart = obj:IsA("MeshPart") and obj or obj:FindFirstChildWhichIsA("MeshPart", true)
    
    if meshPart then
        -- Hapus SurfaceAppearance lama jika ada
        local existing = meshPart:FindFirstChildWhichIsA("SurfaceAppearance")
        if existing then existing:Destroy() end

        -- Buat SurfaceAppearance baru dengan EmissiveMask
        local sa = Instance.new("SurfaceAppearance")
        sa.Name = "EmissivePBR"
        sa.AlphaMode = Enum.AlphaMode.Transparency
        
        -- Properti Tekstur
        -- sa.ColorMap = "${diffuseAssetId}"
        sa.EmissiveMaskContent = "${emissiveAssetId}"
        sa.EmissiveStrength = ${emissiveStrength}
        sa.EmissiveTint = Color3.fromRGB(255, 255, 255)
        
        sa.Parent = meshPart
        print("[EmissiveStudio] Berhasil memasang EmissiveMask pada: " .. meshPart.Name)
    else
        warn("[EmissiveStudio] " .. obj.Name .. " bukan merupakan MeshPart!")
    end
end
`;
  }
}
